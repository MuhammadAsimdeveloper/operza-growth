import type { FieldCondition, FormField, WorkspaceState } from './types';

const now = new Date();

/** Date helper: today + offset days, at a given hour. */
function day(offset: number, hour = 10, minute = 0): string {
  const d = new Date(now);
  d.setDate(d.getDate() + offset);
  d.setHours(hour, minute, 0, 0);
  return d.toISOString();
}

function minutesAgo(n: number): string {
  return new Date(now.getTime() - n * 60_000).toISOString();
}

function weekdays(start: string, end: string, days = [1, 2, 3, 4, 5]) {
  return days.map((weekday) => ({ weekday, start, end }));
}

function field(
  id: string,
  label: string,
  type: FormField['type'],
  required = false,
  options: string[] = [],
  showIf?: FieldCondition,
  points?: Record<string, number>,
): FormField {
  return { id, label, type, required, options, ...(showIf ? { showIf } : {}), ...(points ? { points } : {}) };
}

